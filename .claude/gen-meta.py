# Regenerates js/catalog-meta.js (name + tagline per engine) from the engine modules,
# so the home page can show engine cards without loading every 3D module.
import re, json, glob, os
meta = {}
for f in sorted(glob.glob('js/engines/*.js')):
    s = open(f, encoding='utf-8').read()
    def field(k):
        m = re.search(r"^\s{2}%s:\s*(['\"])(.*?)\1,\s*$" % k, s, re.M)
        return m.group(2).replace("\'", "'") if m else None
    i = field('id')
    if not i: continue
    meta[i] = {'name': field('name'), 'tagline': field('tagline'), 'file': os.path.basename(f)[:-3]}
out = '// Generated by .claude/gen-meta.py — do not edit by hand.\nexport const META = ' + json.dumps(meta, ensure_ascii=False, indent=2) + ';\n'
open('js/catalog-meta.js', 'w', encoding='utf-8').write(out)
print(len(meta), 'engines;', [k for k, v in meta.items() if not v['tagline']], 'without tagline')
